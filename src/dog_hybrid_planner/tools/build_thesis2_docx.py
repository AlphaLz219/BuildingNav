def insert_paragraph_after(paragraph, text="", style=None):
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = paragraph.__class__(new_p, paragraph._parent)
    if style is not None:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def insert_paragraph_before(paragraph, text="", style=None):
    new_p = OxmlElement("w:p")
    paragraph._p.addprevious(new_p)
    new_para = paragraph.__class__(new_p, paragraph._parent)
    if style is not None:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def insert_heading_after(paragraph, text, level):
    style = f"Heading {level}"
    return insert_paragraph_after(paragraph, text, style)


def insert_picture_after(paragraph, image_path, width=5.8):
    p = insert_paragraph_after(paragraph, "", "Normal")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(image_path, width=Inches(width))
    return p


def set_body_format(paragraph):
    paragraph.paragraph_format.first_line_indent = Pt(24)
    paragraph.paragraph_format.line_spacing = 1.25
    for run in paragraph.runs:
        run.font.name = "宋体"
        run.font.size = Pt(12)


def add_body_after(anchor, text):
    last = anchor
    for para in [p.strip() for p in text.split("\n") if p.strip()]:
        last = insert_paragraph_after(last, para, "Normal")
        set_body_format(last)
    return last


def add_body_before(ref_para, text):
    last = None
    for para in [p.strip() for p in text.split("\n") if p.strip()]:
        p = insert_paragraph_before(ref_para, para, "Normal")
        set_body_format(p)
        last = p
    return last


def find_paragraph(doc, exact_text):
    for p in doc.paragraphs:
        if p.text.strip() == exact_text:
            return p
    raise ValueError(f"Cannot find paragraph: {exact_text}")


def insert_table_before(doc, ref_para, rows):
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = "Table Grid"
    for r, row in enumerate(rows):
        for c, value in enumerate(row):
            cell_p = table.cell(r, c).paragraphs[0]
            cell_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = cell_p.add_run(str(value))
            run.font.size = Pt(9)
            if r == 0:
                run.bold = True
    ref_para._p.addprevious(table._tbl)
    return table


